"""Source confidence and field lineage documentation for WARIS.

This module documents how each WARIS model field is sourced, whether it is
synthetic, blended, live/source-backed, metadata-only, or governance-derived.

The goal is not to certify data quality. The goal is to make source lineage,
confidence, limitations, and replacement priorities explicit for analyst review.

Current official-data posture:
- Ukrstat GRP oblast baseline candidates are official SDMX-derived artifacts.
- Unit/scale evidence supports the interpretation of GRP._Z.A as annual gross
  regional product in million UAH.
- The official baseline validation gate currently supports GO for controlled
  benchmark integration only.
- The official merge-review layer currently recommends benchmark_only as the
  current posture.
- The official benchmark review memo documents the benchmark_only posture,
  official-vs-synthetic gap findings, and scoring prohibition in plain language.
- Expanded Prozorro procurement features are review-only candidate artifacts.
- Wartime AML/CFT typology artifacts are literature-support references only.
- Official FIU/SFMS context artifacts are official source-support context only.
- Analyst-review, false-positive, source-freshness, and run-manifest artifacts
  are operational-control/documentation artifacts only.
- Official baseline-to-Prozorro, official baseline-to-wartime-typology,
  official baseline-to-FIU/SFMS, and official baseline-to-operational-controls
  context bridges are review artifacts only.
- Official GRP values remain prohibited from risk-layer calculation, composite
  scoring, risk-band assignment, and Monte Carlo score simulation until
  transformation logic, SME review, and scoring change control are complete.
- Expanded procurement features, wartime typology references, official FIU/SFMS
  context, and operational-control artifacts remain prohibited from direct
  scoring use until coverage, mapping quality, measurable indicator design,
  SME review, and scoring change control are complete.
"""

