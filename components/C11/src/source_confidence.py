def build_source_confidence_assessment(field_register: pd.DataFrame) -> pd.DataFrame:
    """Summarize source confidence by model area and source type."""
    ensure_dirs([TABLE_DIR])

    df = field_register.copy()

    confidence_rank = {
        "High": 5,
        "Medium": 4,
        "Medium-Low": 3,
        "Low": 2,
        "Unknown": 1,
    }

    priority_rank = {
        "High": 3,
        "Medium": 2,
        "Low": 1,
    }

    df["confidence_score_numeric"] = df["confidence_level"].map(confidence_rank).fillna(1)
    df["replacement_priority_numeric"] = df["replacement_priority"].map(priority_rank).fillna(1)

    assessment = (
        df.groupby(["model_area", "current_source_type"], as_index=False)
        .agg(
            field_count=("field_name", "count"),
            avg_confidence_score=("confidence_score_numeric", "mean"),
            max_replacement_priority=("replacement_priority_numeric", "max"),
        )
        .sort_values(
            ["max_replacement_priority", "avg_confidence_score"],
            ascending=[False, True],
        )
    )

    assessment["confidence_interpretation"] = assessment["avg_confidence_score"].apply(
        lambda x: (
            "Higher confidence"
            if x >= 4.5
            else "Moderate confidence"
            if x >= 3.5
            else "Limited confidence"
            if x >= 2.5
            else "Low confidence"
        )
    )

    assessment["replacement_priority_interpretation"] = assessment[
        "max_replacement_priority"
    ].apply(
        lambda x: (
            "High replacement priority"
            if x >= 3
            else "Medium replacement priority"
            if x >= 2
            else "Low replacement priority"
        )
    )

    assessment.to_csv(SOURCE_CONFIDENCE_TABLE, index=False)
    return assessment


