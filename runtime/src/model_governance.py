def _ukrstat_official_baseline_status() -> dict[str, object]:
    """Summarize official Ukrstat baseline candidate evidence for governance.

    This does not validate or blend official values. It only checks whether the
    current run produced the validation-only official baseline artifacts.
    """
    candidates = _load_optional_table(UKRSTAT_OBLAST_BASELINE_CANDIDATES_TABLE)
    probes = _load_optional_table(UKRSTAT_OBLAST_BASELINE_PROBE_RESULTS_TABLE)
    parsed = _load_optional_table(UKRSTAT_CONFIRMED_SERIES_PARSED_TABLE)

    candidate_count = 0 if candidates is None else len(candidates)
    probe_count = 0 if probes is None else len(probes)
    parsed_count = 0 if parsed is None else len(parsed)

    successful_probe_count = 0
    probes_with_observations = 0

    if probes is not None and not probes.empty:
        if "success_status" in probes.columns:
            successful_probe_count = int(
                probes["success_status"]
                .astype(str)
                .str.lower()
                .eq("true")
                .sum()
            )

        if "has_observations" in probes.columns:
            probes_with_observations = int(
                probes["has_observations"]
                .astype(str)
                .str.lower()
                .eq("true")
                .sum()
            )

    current_use_values = []
    validation_values = []

    if candidates is not None and not candidates.empty:
        if "current_use_in_scoring" in candidates.columns:
            current_use_values = (
                candidates["current_use_in_scoring"]
                .fillna("")
                .astype(str)
                .drop_duplicates()
                .tolist()
            )

        if "validation_status" in candidates.columns:
            validation_values = (
                candidates["validation_status"]
                .fillna("")
                .astype(str)
                .drop_duplicates()
                .tolist()
            )

    has_candidate_layer = candidate_count > 0

    return {
        "candidate_count": candidate_count,
        "probe_count": probe_count,
        "successful_probe_count": successful_probe_count,
        "probes_with_observations": probes_with_observations,
        "parsed_count": parsed_count,
        "has_candidate_layer": has_candidate_layer,
        "current_use_values": current_use_values,
        "validation_values": validation_values,
    }


def _official_baseline_validation_gate_status() -> dict[str, object]:
    """Summarize official baseline validation gate outputs for governance."""
    register = _load_optional_table(OFFICIAL_BASELINE_VALIDATION_REGISTER_TABLE)
    summary = _load_optional_table(OFFICIAL_BASELINE_VALIDATION_SUMMARY_TABLE)
    readiness = _load_optional_table(OFFICIAL_BASELINE_READINESS_DECISION_TABLE)
    geography = _load_optional_table(OFFICIAL_BASELINE_GEOGRAPHY_CROSSWALK_CHECK_TABLE)
    period = _load_optional_table(OFFICIAL_BASELINE_PERIOD_COVERAGE_TABLE)

    pass_count = 0
    review_required_count = 0
    partial_count = 0
    high_or_critical_blocking_count = 0

    if register is not None and not register.empty and "status" in register.columns:
        status = register["status"].fillna("").astype(str).str.lower()
        pass_count = int(status.eq("pass").sum())
        review_required_count = int(status.eq("review_required").sum())
        partial_count = int(status.eq("partial").sum())

        if "severity" in register.columns:
            severity = register["severity"].fillna("").astype(str).str.lower()
            high_or_critical_blocking_count = int(
                (
                    status.isin(["review_required", "partial"])
                    & severity.isin(["high", "critical"])
                ).sum()
            )

    decision = "not_available"
    approved_current_use = "not_available"
    prohibited_current_use = "not_available"
    rationale = "Validation readiness decision artifact not found."

    if readiness is not None and not readiness.empty:
        first = readiness.iloc[0]
        decision = str(first.get("decision", "not_available"))
        approved_current_use = str(first.get("approved_current_use", "not_available"))
        prohibited_current_use = str(first.get("prohibited_current_use", "not_available"))
        rationale = str(first.get("rationale", ""))

    overall_summary = "not_available"

    if summary is not None and not summary.empty:
        if {"summary_area", "value"}.issubset(summary.columns):
            overall_rows = summary[
                summary["summary_area"].fillna("").astype(str).eq("Overall readiness")
            ]
            if not overall_rows.empty:
                overall_summary = str(overall_rows.iloc[0].get("value", "not_available"))
            else:
                overall_summary = str(summary.iloc[0].get("value", "not_available"))

    geography_issue_count = 0
    if geography is not None and not geography.empty and "coverage_status" in geography.columns:
        geography_issue_count = int(
            geography["coverage_status"]
            .fillna("")
            .astype(str)
            .isin(["missing", "unexpected", "duplicate_candidate_rows"])
            .sum()
        )

